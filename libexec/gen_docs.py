#!/usr/bin/env python3
"""Generate docs/COMMANDS.md command reference from dotfiles code declarations."""

from __future__ import annotations

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


def get_dot_subcommands() -> list[tuple[str, str, str]]:
    """Extract `dot` CLI subcommands and descriptions."""
    status_file = REPO_ROOT / "cli" / "status.py"
    text = status_file.read_text(encoding="utf-8")
    m = re.search(r"SUBCOMMANDS_TABLE:[^=]*=\s*\(([\s\S]*?)\n\)", text)
    if not m:
        return []
    entries = []
    for line in m.group(1).splitlines():
        row_m = re.search(r'\(\s*"([^"]+)"\s*,\s*"([^"]*)"\s*,\s*"([^"]+)"\s*\)', line)
        if row_m:
            entries.append((row_m.group(1), row_m.group(2), row_m.group(3)))
    return entries


def get_bin_utilities() -> list[tuple[str, str]]:
    """Extract standalone bin/* executables and their `# Description:` headers."""
    bin_dir = REPO_ROOT / "bin"
    utilities = []
    for p in sorted(bin_dir.iterdir()):
        if not p.is_file() or p.name.startswith("."):
            continue
        desc = "Standalone executable"
        try:
            for line in p.read_text(encoding="utf-8", errors="ignore").splitlines()[:5]:
                if line.startswith("# Description:"):
                    desc = line.split(":", 1)[1].strip()
                    break
        except OSError:
            pass
        utilities.append((p.name, desc))
    return utilities


def _parse_zsh_function_headers() -> dict[str, tuple[str, str]]:
    """Parse header comments and source module filenames from zsh/functions/*.zsh."""
    func_info: dict[str, tuple[str, str]] = {}
    for zf in sorted((REPO_ROOT / "zsh" / "functions").glob("*.zsh")):
        text = zf.read_text(encoding="utf-8")
        prev = ""
        for line in text.splitlines():
            line_str = line.strip()
            if line_str.startswith("#"):
                clean = re.sub(r"^#\s*", "", line_str)
                if clean and not clean.startswith(("Usage:", "===", "---")) and not prev:
                    prev = clean
            elif re.match(r"^(,|[\w-]+)\(\)\s*\{", line_str):
                m_fn = re.match(r"^(,|[\w-]+)\(\)", line_str)
                if m_fn and prev:
                    func_info[m_fn.group(1)] = (zf.name, prev)
                prev = ""
            else:
                prev = ""
    return func_info


def get_custom_functions() -> list[tuple[str, str, str, str]]:
    """Extract registered Zsh functions, comma shorthands, suite source, and descriptions."""
    functions_zsh = (REPO_ROOT / "zsh" / "functions.zsh").read_text(encoding="utf-8")
    fn_match = re.search(r"typeset\s+-ga\s+DOTFILES_FUNCTIONS=\s*\(([\s\S]*?)\)", functions_zsh)
    if not fn_match:
        return []

    registered_fns: list[str] = []
    for line in fn_match.group(1).splitlines():
        clean_line = line.split("#", 1)[0].strip()
        registered_fns.extend(clean_line.split())

    comma_zsh = (REPO_ROOT / "zsh" / "functions" / "comma.zsh").read_text(encoding="utf-8")
    shorthands: dict[str, str] = {}
    sh_m = re.search(r"typeset\s+-gA\s+DOTFILES_COMMA_SHORTHANDS=\s*\(([\s\S]*?)\)", comma_zsh)
    if sh_m:
        lines = [
            line.strip()
            for line in sh_m.group(1).splitlines()
            if line.strip() and not line.strip().startswith("#")
        ]
        for line in lines:
            parts = line.split()
            if len(parts) >= 2:
                shorthands[parts[0]] = parts[1]

    func_info = _parse_zsh_function_headers()
    results = []
    for fn in registered_fns:
        shorthand = shorthands.get(fn, f",{fn}" if fn != "," else ",")
        src_file, desc = func_info.get(fn, ("zsh/functions.zsh", "Interactive shell function"))
        results.append((fn, shorthand, src_file, desc))
    return results


def generate_markdown() -> str:
    """Generate complete markdown documentation."""
    lines = [
        "# Dotfiles Command & Function Reference",
        "",
        "> Auto-generated reference generated by `libexec/gen_docs.py`.",
        "> Validated in continuous integration and `./bin/dot test`.",
        "",
        "## 1. `dot` CLI Subcommands",
        "",
        "| Subcommand | Alias | Description |",
        "| :--- | :--- | :--- |",
    ]
    for cmd, alias, desc in get_dot_subcommands():
        alias_str = f"`{alias}`" if alias else "-"
        lines.append(f"| `{cmd}` | {alias_str} | {desc} |")

    lines.extend([
        "",
        "## 2. Interactive Shell Functions & Comma Shorthands",
        "",
        "| Function | Comma Shorthand | Module | Description |",
        "| :--- | :--- | :--- | :--- |",
    ])
    for fn, short, mod, desc in get_custom_functions():
        lines.append(f"| `{fn}` | `{short}` | `{mod}` | {desc} |")

    lines.extend([
        "",
        "## 3. Standalone Executables (`bin/*`)",
        "",
        "| Utility | Description |",
        "| :--- | :--- |",
    ])
    for name, desc in get_bin_utilities():
        lines.append(f"| `{name}` | {desc} |")

    lines.append("")
    return "\n".join(lines)


def main() -> int:
    """Write docs/COMMANDS.md."""
    output_path = REPO_ROOT / "docs" / "COMMANDS.md"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    content = generate_markdown()
    output_path.write_text(content, encoding="utf-8")
    print(f"Generated {output_path} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
